SELECT i.paper_id, m.id FROM icl_papers i JOIN papers p ON p.id = i.paper_id, methods m
WHERE m.slug = 'few-shot-prompting'
ON CONFLICT (paper_id, method_id) DO NOTHING;

INSERT INTO paper_method_evidence (paper_id, method_id, evidence_type)
SELECT i.paper_id, m.id, 'manual' FROM icl_papers i JOIN papers p ON p.id = i.paper_id, methods m
WHERE m.slug = 'few-shot-prompting'
ON CONFLICT (paper_id, method_id, evidence_type) DO UPDATE SET last_seen_at = now();

