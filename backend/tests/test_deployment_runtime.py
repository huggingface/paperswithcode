def test_staging_candidate_smoke_leaves_spa_to_nginx(monkeypatch):
    requested: list[str] = []

    def request(url: str, *, allow_redirects: bool = True):
        requested.append(url)
        if url.endswith("/health"):
            return 200, {}, b'{"release_id":"release-staging"}'
